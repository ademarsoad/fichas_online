    <p>A rosca direta é um exercício clássico e isolado focado no fortalecimento e hipertrofia dos bíceps. 
        Pode ser feito com barra (reta ou W), halteres ou polia.Passo a Passo <br>
        1 - Posição inicial: Fique em pé, com os pés afastados na largura dos ombros e os joelhos levemente flexionados. Segure a barra ou halteres com as palmas das 
        mãos viradas para a frente (pegada supinada).<br>
        2 - Postura: Estufe o peito, mantenha os ombros encaixados para trás e o abdômen 
        contraído.<br>
        3 - Subida (fase concêntrica): Flexione os cotovelos elevando o peso até a altura dos ombros. Mantenha os 
        cotovelos travados e próximos ao tronco durante todo o movimento.<br>
         4 - Descida (fase excêntrica): Abaixe o peso de forma 
        lenta e controlada até quase a extensão total dos braços.</p>
